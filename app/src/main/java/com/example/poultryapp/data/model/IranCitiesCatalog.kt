    /**
     * List of all 31 Iranian provinces sorted alphabetically in Persian.
     */
    fun getAllProvinces(): List<String> = provincesList

    /**
     * Get all cities belonging to a specified province.
     */
    fun getCitiesForProvince(province: String): List<IranCity> {
        return CITIES.filter { it.province.equals(province.trim(), ignoreCase = true) }
            .sortedBy { it.name }
    }

    /**
     * Find a city by exact or trimmed name.
     */
    fun findCityByName(name: String): IranCity? {
        val clean = name.trim()
        if (clean.isBlank()) return null
        return CITIES.firstOrNull { it.name.equals(clean, ignoreCase = true) }
            ?: CITIES.firstOrNull { it.name.contains(clean, ignoreCase = true) || clean.contains(it.name, ignoreCase = true) }
    }

    /**
     * Searches cities across all provinces or within a specific province.
     */
    fun searchCities(query: String, province: String? = null): List<IranCity> {
        val clean = query.trim()
        val source = if (!province.isNullOrBlank()) getCitiesForProvince(province) else CITIES
        if (clean.isBlank()) return source
        return source.filter {
            it.name.contains(clean, ignoreCase = true) ||
            it.province.contains(clean, ignoreCase = true)
        }.sortedBy { it.name }
    }

    /**
     * Finds the nearest Iranian city to the provided GPS coordinates using
     * Haversine spherical distance calculation.
     */
    fun findNearestCity(lat: Double, lon: Double): IranCity {
        var minDistance = Double.MAX_VALUE
        var nearest = CITIES.first()

        for (city in CITIES) {
            val d = haversineDistanceKm(lat, lon, city.lat, city.lon)
            if (d < minDistance) {
                minDistance = d
                nearest = city
            }
        }
        return nearest
    }

    /**
     * Returns the climatological seasonal average temperature for a city.
     */
    fun getSeasonalAvgTemp(city: IranCity, season: FarmSeason = JalaliDateHelper.getCurrentSeason()): Double {
        return city.getTempForSeason(season)
    }

    /**
     * Haversine distance in kilometers.
     */
    private fun haversineDistanceKm(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val r = 6371.0 // Earth radius in km
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = sin(dLat / 2) * sin(dLat / 2) +
                cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) *
                sin(dLon / 2) * sin(dLon / 2)
        val c = 2 * atan2(sqrt(a), sqrt(1 - a))
        return r * c
    }
