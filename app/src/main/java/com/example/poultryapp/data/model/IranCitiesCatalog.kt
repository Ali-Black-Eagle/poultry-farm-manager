    fun getTempForSeason(season: FarmSeason): Double {
        return when (season) {
            FarmSeason.SPRING -> springTemp
            FarmSeason.SUMMER -> summerTemp
            FarmSeason.AUTUMN -> autumnTemp
            FarmSeason.WINTER -> winterTemp
        }
    }
}

