    /**
     * جستجوی سریع اصطلاحات بر اساس نام یا کلید
     */
    fun findTerm(query: String): GlossaryTerm? {
        val q = query.trim().lowercase()
        return allTerms.firstOrNull { term ->
            term.key.lowercase() == q ||
                    term.titleFa.lowercase() == q ||
                    term.titleEn?.lowercase() == q ||
                    term.synonyms.any { it.lowercase() == q }
        }
    }

    /**
     * اسکن یک متن و شناسایی خودکار تمام واژه‌های تخصصی موجود در آن
     */
    fun findTermsInText(text: String): List<GlossaryTerm> {
        if (text.isBlank()) return emptyList()
        val found = mutableListOf<GlossaryTerm>()
        val lowerText = text.lowercase()

        for (term in allTerms) {
            val hasKey = lowerText.contains(term.key.lowercase())
            val hasSynonym = term.synonyms.any { lowerText.contains(it.lowercase()) }
            if (hasKey || hasSynonym) {
                found.add(term)
            }
        }
        return found
    }
