        val q = questionText.lowercase()
        val ageStr = if (ageDays != null && ageDays > 0) "در سن $ageDays روزگی" else ""
        val countStr = if (flockCount != null && flockCount > 0) "برای گله $flockCount قطعه‌ای" else ""

        val sb = StringBuilder()
        sb.append("📋 راهنمای فوری کارشناس پرورش $ageStr $countStr:\n\n")

        when {
            q.contains("خون") || q.contains("اسهال") || q.contains("مدفوع") -> {
