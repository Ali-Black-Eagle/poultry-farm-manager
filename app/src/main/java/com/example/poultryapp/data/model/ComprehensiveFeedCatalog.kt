enum class FeedCategory(val titleFa: String, val iconRes: Int) {
    GRAINS("غلات و دانه‌ها", R.drawable.ic_feed_corn),
    PLANT_PROTEIN("کنجاله‌ها و پروتئین گیاهی", R.drawable.ic_feed_soybean),
    ANIMAL_PROTEIN("پروتئین‌های حیوانی", R.drawable.ic_feed_fishmeal),
    FATS_OILS("روغن‌ها و چربی‌ها", R.drawable.ic_feed_oil),
    MINERALS("مواد معدنی و بافرها", R.drawable.ic_feed_limestone),
    AMINO_ACIDS("اسیدهای آمینه سنتتیک", R.drawable.ic_feed_amino),
    PREMIXES("پرمیکس‌ها و مکمل‌ها", R.drawable.ic_feed_premix),
    ADDITIVES("افزودنی‌ها و محافظ‌ها", R.drawable.ic_feed_additive),
    CUSTOM("مواد سفارشی مرغدار", R.drawable.ic_feed_custom);

    companion object {
        fun fromString(str: String?): FeedCategory {
            if (str == null) return GRAINS
            return entries.firstOrNull { it.name.equals(str, ignoreCase = true) || it.titleFa.equals(str, ignoreCase = true) } ?: GRAINS
        }
    }
}

